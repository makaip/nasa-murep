"""Build RESULTS.md at the repo root (not outputs/redo: Windows paths are case-insensitive and would clash with results.md): the single index of key numbers, figures, known
issues and changelog. Values are read from outputs/redo/results.json, so rerunning this
script after any rerun keeps the index in sync. Add a CHANGELOG line whenever results change.
"""

import json

import common as c

CHANGELOG = [
    ("2026-11-07", "Initial redo on one consistent setup (v4, 2010-2019, depth >= 10 m, monthly zone maps): "
                   "-1 sigma, IF (pipeline5), K-means, DBSCAN, inside/outside stats, figures (commit 15054e9)."),
    ("2026-11-07", "Added K-means preprocessing comparison (exact old-notebook replication, unscaled vs StandardScaler vs "
                   "Yeo-Johnson), provenance table, violin/model check with correction (commit 4a633b0)."),
    ("2026-11-07", "Added corr_diff.py significance tests of rho_in - rho_out (naive / n_eff Fisher z, block bootstrap, "
                   "Wilcoxon); created this index; report.py now keeps hand-written sections in report_static.md."),
]

FIGS = [
    ("violins_iforest", "Inside vs outside IF zone by calendar month, 2010-2019 pooled: a_CDOM(412), S275-295, S300-600, log10 Chl.",
     "Main text: replaces the IF violin figure (summary across years)."),
    ("violins_sigma", "Same layout for the -1 sigma SST zone (new monthly spatial rule).",
     "Main text or supplement, next to the IF violins, for the method comparison."),
    ("violins_kmeans", "Same layout for global K-means (k=3, StandardScaler, monthly maps); the zone is mostly a winter cluster.",
     "Supplement (K-means section)."),
    ("violins_kmeans_month", "Same layout for per-month K-means (k=3, standardized within each month-year).",
     "Supplement (K-means section)."),
    ("scatter_a412_chl_loglog", "a_CDOM(412) vs Chl-a, log-log, inside vs outside, -1 sigma and IF, pooled and May 2018, with Spearman rho.",
     "Main text: replaces the CDOM vs Chl scatter plot (answers the log-log request)."),
    ("zonemap_2018_07", "-1 sigma vs IF zone maps, July 2018, on monthly-mean SST, 10 m contour.",
     "Main text: method comparison map (representative month)."),
    ("zonemap_2018_05", "Same for May 2018.", "Supplement."),
]
# Paper figure numbers are not filled in: the draft (.docx) was deliberately not opened.


def main():
    r = json.load(open(c.OUT_DIR / "results.json"))
    cov, st, cmp_ = r["coverage"], r["stats"], r["comparison"]
    ms = ["sigma", "iforest", "kmeans", "kmeans_month", "dbscan"]
    L = ["# Yucatan redo analysis - results index", "",
         "Single index of every key number in the redo (branch `redo-analysis`, repo nasa-murep). Generated by "
         "`yucatan/experiments/redo/results_index.py` from `yucatan/outputs/redo/results.json`; full tables in "
         "`yucatan/outputs/redo/results.md`. Run everything with `.venv\\Scripts\\python.exe yucatan\\experiments\\redo\\run_all.py`, "
         "then this script.", "", "## Changelog", ""]
    L += [f"- {d}: {t}" for d, t in CHANGELOG]
    s = r["setup"]
    L += ["", "## Data and setup", "",
          "| Item | Value | Script | Output |", "|---|---|---|---|",
          f"| Data | v4 pickle, {s['n_days']} days {s['first_day']}..{s['last_day']}, {s['grid'][0]}x{s['grid'][1]} grid | redo/common.py | results.json `setup` |",
          f"| Depth mask | bathymetry <= -10 m: {s['n_deep_pixels']:,} pixels | redo/common.py | results.json `setup` |",
          "| Zone maps | one per month-year (120) + 12 climatology; daily pixels labelled by their month-year map | redo/sigma.py, iforest.py, kmeans.py, dbscan.py | outputs/redo/cache/zones/*.npz (git-ignored) |",
          f"| IF model | {r['iforest']['model']} (pipeline4 run as sensitivity) | redo/iforest.py | results.json `iforest` |",
          "", "## Method coverage", "",
          "| Metric | " + " | ".join(ms) + " | Script | Output |", "|---|" + "---|" * (len(ms) + 2)]
    rows = [("% of deep pixel-months in zone", "pct_overall_pixel_months", "{:.2f}"),
            ("Month-years with zone >= 1 px (/120)", "n_month_years_with_zone_ge1px", "{}"),
            ("Month-years with zone >= 1% (/120)", "n_month_years_with_zone_ge1pct", "{}"),
            ("Climatology months with zone (/12)", "n_clim_months_with_zone", "{}"),
            ("Share of zone pixel-months in May-Sep", "frac_zone_pixels_in_May_Sep", "{:.3f}")]
    for lab, key, f in rows:
        L.append(f"| {lab} | " + " | ".join(f.format(cov[m][key]) if cov[m][key] is not None else "-" for m in ms)
                 + " | redo/report.py | results.md section 1; results.json `coverage` |")
    L += ["", "## Inside vs outside (daily pixels, pooled 2010-2019)", "",
          "| Method | Variable | median in | median out | Cliff's delta | Script | Output |", "|---|---|---|---|---|---|---|"]
    for m in ("iforest", "sigma", "kmeans", "kmeans_month"):
        for v, nm in (("a412", "a_CDOM(412)"), ("s275", "S275-295"), ("s300", "S300-600"), ("log10_chl", "log10 Chl")):
            p = st[m]["pooled"][v]
            L.append(f"| {m} | {nm} | {p['median_in']:.4f} | {p['median_out']:.4f} | {p['cliffs_delta']:+.3f} | redo/stats.py | results.md section 3; results.json `stats.{m}.pooled` |")
    L.append("\nPer-month values (May-Sep |delta| 0.7-0.9 for IF) are in results.md section 3 and results.json `stats.<method>.by_month`.")
    L += ["", "## a_CDOM vs Chl-a correlation", "",
          "| Method | rho in | rho out | rho in lower/upper half of a412 | Script | Output |", "|---|---|---|---|---|---|"]
    for m in ("iforest", "sigma"):
        cr = st[m]["pooled"]["corr_a412_chl"]
        L.append(f"| {m} | {cr['inside']['spearman']:.3f} | {cr['outside']['spearman']:.3f} | "
                 f"{cr['inside']['lower_half']['spearman']:.2f} / {cr['inside']['upper_half']['spearman']:.2f} | redo/stats.py | results.md section 3 |")
    q = st["sigma"]["taper_all_pixels_quartiles"]
    L.append(f"\nTaper, all classified pixels, rho by a412 quartile: " + ", ".join(f"Q{x['quartile']} {x['spearman']:.2f}" for x in q) +
             " (redo/stats.py, results.md section 3). Interpretation: largely algorithmic. All CDOM products and Chl-a are blue/green "
             "band-ratio functions (results.md section 5).")
    cd = r.get("corr_diff")
    if cd:
        L += ["", "### Significance of rho_in - rho_out (redo/corr_diff.py -> results.md section 9, results.json `corr_diff`)", "",
              "| Method | Scope | diff | a naive Fisher p | b1 Bretherton n_eff p | b2 month-year-unit p | c1 month-year bootstrap 95% CI (p) | c2 tile bootstrap 95% CI (p) | d Wilcoxon n, p |",
              "|---|---|---|---|---|---|---|---|---|"]
        pf = lambda x: "-" if x is None else ("<1e-300" if x == 0 else f"{x:.1e}")
        for m in ("iforest", "sigma"):
            for sc in ("all", "May-Sep"):
                x = cd[m].get(sc, {})
                if "diff" not in x:
                    continue
                b1, b2 = x["b1_fisher_bretherton"], x["b2_fisher_monthyear_units"]
                c1, c2, d = x["c1_boot_monthyear"], x["c2_boot_monthyear_x_tile"], x["d_wilcoxon_monthyears"]
                L.append(f"| {m} | {sc} | {x['diff']:+.3f} | {pf(x['a_naive_fisher']['p'])} | {pf(b1['p']) if b1 else '-'} | "
                         f"{pf(b2['p']) if b2 else '-'} | [{c1['ci95'][0]:+.3f}, {c1['ci95'][1]:+.3f}] ({pf(c1['p'])}) | "
                         f"[{c2['ci95'][0]:+.3f}, {c2['ci95'][1]:+.3f}] ({pf(c2['p'])}) | {d['n']}, {pf(d['p'])} |")
        L.append("\nRecommended for the paper: the month-year block bootstrap CI (c1), with the Wilcoxon test over month-years (d) "
                 "as support. Both treat the month-year as the independent unit, which matches how zones are defined, and make no "
                 "parametric autocorrelation model. Report the naive p only as an illustration of why it is not used.")
    io = cmp_["iou_sigma_vs_iforest"]
    L += ["", "## Method agreement", "",
          f"- -1 sigma vs IF zone IoU: mean {io['mean']:.3f}, median {io['median']:.3f}; {100*io['frac_iforest_zone_inside_sigma_zone']:.1f}% of IF zone pixels lie inside the -1 sigma zone (redo/report.py; results.md section 4; results.json `comparison`).",
          f"- IF pipeline5 vs pipeline4 IoU: mean {cmp_['iou_iforest_p5_vs_p4']['mean']:.3f}, median {cmp_['iou_iforest_p5_vs_p4']['median']:.3f} (redo/iforest.py + report.py)."]
    k = r["kmeans"]["global"]
    L += ["", "## K-means", "",
          f"- Monthly-map K-means (redo/kmeans.py, StandardScaler): squared-separation share SST/Chl/SSL k=3 = "
          f"{100*k['by_k']['3']['pairwise_sq_sep_share']['sst']:.1f} / {100*k['by_k']['3']['pairwise_sq_sep_share']['log10_chl']:.1f} / "
          f"{100*k['by_k']['3']['pairwise_sq_sep_share']['ssl']:.1f}%; PCA {', '.join(f'{100*x:.1f}' for x in k['pca_explained_variance_ratio'])}% (results.md section 2a)."]
    kc = r.get("kmeans_compare")
    if kc:
        L += ["", "| Variant (redo/kmeans_compare.py) | k | sep. share Chl/SST/SSL % | PC1 % | silhouette | cold share May-Sep | month-years cold >= 1% |",
              "|---|---|---|---|---|---|---|"]
        for v, x in kc.items():
            for kk in ("2", "3"):
                b = x["by_k"][kk]; sh = b["sq_sep_share"]
                L.append(f"| {v} | {kk} | {100*sh['log10_chl']:.1f}/{100*sh['sst']:.1f}/{100*sh['ssl']:.1f} | "
                         f"{100*x['pca_explained_variance_ratio'][0]:.1f} | {b['silhouette_20k']:.3f} | {100*b['cold_share_in_May_Sep']:.1f}% | {b['month_years_cold_ge1pct']} |")
        L.append("\nThe ~97% SST separation reproduces only unscaled (a0/a, about 99%). It is a units effect "
                 "(SST raw variance about 94% of the total). Output: results.md section 6; results.json `kmeans_compare`.")
    db = r["dbscan"]["summary"]
    L += ["", "## DBSCAN (appendix)", "",
          f"- eps 0.28, min_samples 50, per month-year: clusters {db['n_clusters_distribution']}; noise mean {100*db['noise_fraction_mean']:.1f}%; "
          f"separate cold cluster in {db['month_years_with_separate_cold_cluster']}/120 month-years; consecutive-month zone IoU {db['consecutive_zone_iou_mean_where_defined']:.3f} "
          "(redo/dbscan.py; results.md section 2d)."]
    si = r["iforest"]["surrogate_importance_summary"]
    L += ["", "## IF feature importances", "",
          f"- Surrogate RF per month-year: SST anomaly {100*si['sst_anom_mean']:.1f}% +/- {100*si['sst_anom_sd']:.1f}%, "
          f"SSL anomaly {100*si['ssl_anom_mean']:.1f}% +/- {100*si['ssl_anom_sd']:.1f}% (redo/iforest.py; results.md section 2c)."]
    L += ["", "## Figures (yucatan/outputs/redo/figs, PNG + PDF, 600 dpi; produced by redo/figures.py)", "",
          "Paper figure numbers are not filled in because the draft (.docx) was not opened; the column gives the suggested placement.", "",
          "| File | Description | Suggested paper use / replaces |", "|---|---|---|"]
    for f, d, use in FIGS:
        L.append(f"| figs/{f}.png / .pdf | {d} | {use} |")
    L += ["", "PNGs are git-ignored by the repo's global `*.png` rule; the PDFs are committed and the PNGs exist on disk.", "",
          "## Known issues", "",
          "1. `yucatan/figs/bayth_preclassified.pkl` (used by the current violins/maps on main) was produced with `iforest_pipeline4`; all code "
          "points to pipeline5. Violins and maps agree with each other but are pipeline4. Fix: choose a model and rerun `bayth_classification.py`.",
          "2. `experiments/visualization/scatterplots/common.py` still classifies per day (pipeline5, 95th percentile, -20 m), so the "
          "scatterplots on main do not match the violins/maps.",
          "3. The redo -1 sigma rule (monthly spatial mean - 1 sd, depth >= 10 m) differs from the old paper rule in nasa-murep-local "
          "`w_hist` (week-of-year mean - 1 sd pooled over all years/pixels, v3, no depth mask). Numbers are not comparable one-to-one.",
          "4. `redo/kmeans.py` is a reimplementation (monthly maps, no SSL blur), not the old notebook; the exact replica is `redo/kmeans_compare.py`.",
          "5. a_CDOM and both slopes are deterministic functions of Rrs443/Rrs547, and Chl-a is a band ratio too, so CDOM-Chl "
          "correlations and their inside/outside differences are largely algorithmic.",
          "6. v4 has no negative a_CDOM (clipped to [0, 1] in preprocessing).",
          "7. Section 6 of results.md (K-means comparison) is static text in `redo/report_static.md`; this index reads the live numbers from results.json."]
    (c.YUCATAN_DIR.parent / "RESULTS.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("RESULTS.md written")


if __name__ == "__main__":
    main()
